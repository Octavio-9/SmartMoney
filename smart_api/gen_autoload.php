<?php
/**
 * Proper autoload generator using composer.lock + installed.php paths.
 * Fixes loading order of autoload files by prioritizing dependency files.
 */

$vendorDir = realpath(__DIR__ . '/vendor');
$composerDir = $vendorDir . '/composer';

// Read lock file for autoload info
$lock = json_decode(file_get_contents(__DIR__ . '/composer.lock'), true);
$allPkgs = array_merge($lock['packages'], $lock['packages-dev']);

// Read installed.php for actual install paths
$installed = require $composerDir . '/installed.php';

// Build name -> install_path map
$pathMap = [];
foreach ($installed['versions'] as $name => $info) {
    if (isset($info['install_path'])) {
        $p = $info['install_path'];
        // Make absolute if it is relative
        if (!preg_match('/^[A-Z]:/i', $p) && (empty($p) || ($p[0] !== '/' && $p[0] !== '\\'))) {
            $p = $composerDir . '/' . $p;
        }
        $abs = realpath($p);
        if ($abs) $pathMap[$name] = $abs;
    }
}

$psr4 = [];
$psr0 = [];
$classmap = [];
$safeFiles = [];
$otherFiles = [];

foreach ($allPkgs as $pkg) {
    $name = $pkg['name'];
    $al = $pkg['autoload'] ?? [];

    $basePath = $pathMap[$name] ?? null;
    if (!$basePath) continue;

    // PSR-4
    foreach (($al['psr-4'] ?? []) as $ns => $paths) {
        if (!is_array($paths)) $paths = [$paths];
        foreach ($paths as $p) {
            $abs = $basePath . '/' . ltrim($p, '/\\');
            $abs = str_replace('\\', '/', $abs);
            $psr4[$ns][] = $abs;
        }
    }

    // PSR-0
    foreach (($al['psr-0'] ?? []) as $ns => $paths) {
        if (!is_array($paths)) $paths = [$paths];
        foreach ($paths as $p) {
            $abs = $basePath . '/' . ltrim($p, '/\\');
            $abs = str_replace('\\', '/', $abs);
            $psr0[$ns][] = $abs;
        }
    }

    // Classmap — indispensable aux paquets dont des classes vivent hors PSR-4.
    // dompdf en est l'exemple : il declare "classmap": ["lib/"], et c'est la
    // que se trouve Dompdf\Cpdf, sans quoi toute generation de PDF echoue.
    foreach (($al['classmap'] ?? []) as $p) {
        $abs = str_replace('\\', '/', $basePath . '/' . ltrim($p, '/\\'));
        foreach (scanClassmapPath($abs) as $class => $file) {
            if (!isset($classmap[$class])) {
                $classmap[$class] = $file;
            }
        }
    }

    // Files
    foreach (($al['files'] ?? []) as $f) {
        $abs = $basePath . '/' . ltrim($f, '/\\');
        $abs = str_replace('\\', '/', $abs);
        if (strpos($name, 'thecodingmachine/safe') !== false) {
            $safeFiles[md5($abs)] = $abs;
        } else {
            $otherFiles[md5($abs)] = $abs;
        }
    }
}

// Ensure thecodingmachine/safe files are loaded first
$files = array_merge($safeFiles, $otherFiles);

// Add app autoload from composer.json
$appJson = json_decode(file_get_contents(__DIR__ . '/composer.json'), true);
foreach (($appJson['autoload']['psr-4'] ?? []) as $ns => $paths) {
    if (!is_array($paths)) $paths = [$paths];
    foreach ($paths as $p) {
        $abs = __DIR__ . '/' . ltrim($p, '/\\');
        $abs = str_replace('\\', '/', $abs);
        $psr4[$ns][] = $abs;
    }
}
foreach (($appJson['autoload-dev']['psr-4'] ?? []) as $ns => $paths) {
    if (!is_array($paths)) $paths = [$paths];
    foreach ($paths as $p) {
        $abs = __DIR__ . '/' . ltrim($p, '/\\');
        $abs = str_replace('\\', '/', $abs);
        $psr4[$ns][] = $abs;
    }
}

// Write autoload_psr4.php
$out = "<?php\n// autoload_psr4.php @generated by gen_autoload.php\n\n";
$out .= "\$vendorDir = dirname(__DIR__);\n";
$out .= "\$baseDir = dirname(\$vendorDir);\n\n";
$out .= "return " . var_export($psr4, true) . ";\n";
file_put_contents($composerDir . '/autoload_psr4.php', $out);

// Write autoload_namespaces.php
$out = "<?php\n// autoload_namespaces.php @generated by gen_autoload.php\n\n";
$out .= "return " . var_export($psr0, true) . ";\n";
file_put_contents($composerDir . '/autoload_namespaces.php', $out);

// Write autoload_classmap.php
$out = "<?php\n// autoload_classmap.php @generated by gen_autoload.php\n\n";
$out .= "return " . var_export($classmap, true) . ";\n";
file_put_contents($composerDir . '/autoload_classmap.php', $out);
fwrite(STDOUT, 'classmap : ' . count($classmap) . " classes\n");

// Write autoload_files.php
$out = "<?php\n// autoload_files.php @generated by gen_autoload.php\n\n";
$out .= "return " . var_export($files, true) . ";\n";
file_put_contents($composerDir . '/autoload_files.php', $out);

// Write platform_check.php
file_put_contents($composerDir . '/platform_check.php', "<?php\n// Platform check skipped\n");

// Write ClassLoader.php link check
if (!file_exists($composerDir . '/ClassLoader.php')) {
    echo "WARNING: ClassLoader.php not found in vendor/composer\n";
}

// Write autoload_real.php
$autoloadReal = <<<'PHP'
<?php

class ComposerAutoloaderInitSmartMoney {
    private static $loader;

    public static function loadClassLoader($class) {
        if ('Composer\Autoload\ClassLoader' === $class) {
            require __DIR__ . '/ClassLoader.php';
        }
    }

    public static function getLoader() {
        if (null !== self::$loader) {
            return self::$loader;
        }

        require __DIR__ . '/platform_check.php';

        spl_autoload_register(['ComposerAutoloaderInitSmartMoney', 'loadClassLoader'], true, true);
        self::$loader = $loader = new \Composer\Autoload\ClassLoader(\dirname(__DIR__));
        spl_autoload_unregister(['ComposerAutoloaderInitSmartMoney', 'loadClassLoader']);

        $loader->setPsr4('', []);
        
        $map = require __DIR__ . '/autoload_namespaces.php';
        foreach ($map as $namespace => $path) {
            $loader->set($namespace, $path);
        }

        $map = require __DIR__ . '/autoload_psr4.php';
        foreach ($map as $namespace => $path) {
            $loader->setPsr4($namespace, $path);
        }

        $classMap = require __DIR__ . '/autoload_classmap.php';
        if ($classMap) {
            $loader->addClassMap($classMap);
        }

        $loader->register(true);

        $includeFiles = require __DIR__ . '/autoload_files.php';
        foreach ($includeFiles as $fileIdentifier => $file) {
            composerRequireSmartMoney($fileIdentifier, $file);
        }

        return $loader;
    }
}

function composerRequireSmartMoney($fileIdentifier, $file) {
    if (empty($GLOBALS['__composer_autoload_files'][$fileIdentifier])) {
        $GLOBALS['__composer_autoload_files'][$fileIdentifier] = true;
        require $file;
    }
}
PHP;
file_put_contents($composerDir . '/autoload_real.php', $autoloadReal);

// Write vendor/autoload.php
$autoloadPhp = <<<'PHP'
<?php

// autoload.php @generated by gen_autoload.php
require_once __DIR__ . '/composer/autoload_real.php';

return ComposerAutoloaderInitSmartMoney::getLoader();
PHP;
file_put_contents($vendorDir . '/autoload.php', $autoloadPhp);

echo "Done!\n";
echo "PSR-4 namespaces: " . count($psr4) . "\n";
echo "PSR-0 namespaces: " . count($psr0) . "\n";
echo "Files: " . count($files) . "\n";

// Test it
echo "\nTesting autoloader...\n";
try {
    $loader = require $vendorDir . '/autoload.php';
    echo "Autoloader loaded OK\n";
    echo "Can load Illuminate\\Support\\Str: " . (class_exists('Illuminate\\Support\\Str') ? 'YES' : 'NO') . "\n";
    echo "Can load Illuminate\\Foundation\\Application: " . (class_exists('Illuminate\\Foundation\\Application') ? 'YES' : 'NO') . "\n";
    echo "Can load Dompdf\\Cpdf (classmap): " . (class_exists('Dompdf\\Cpdf') ? 'YES' : 'NO') . "\n";
} catch (Throwable $e) {
    echo "Error: " . $e->getMessage() . "\n";
    echo "In: " . $e->getFile() . ":" . $e->getLine() . "\n";
}

/**
 * Construit la carte classe => fichier pour un chemin declare en "classmap",
 * a la maniere du ClassMapGenerator de Composer. Accepte un fichier ou un
 * repertoire, qui est alors parcouru recursivement.
 */
function scanClassmapPath(string $path): array
{
    if (is_file($path)) {
        $files = [$path];
    } elseif (is_dir($path)) {
        $files = [];
        $it = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS)
        );
        foreach ($it as $entry) {
            if ($entry->isFile() && strtolower($entry->getExtension()) === 'php') {
                $files[] = str_replace('\\', '/', $entry->getPathname());
            }
        }
    } else {
        return [];
    }

    $map = [];
    foreach ($files as $file) {
        foreach (extractClassNames($file) as $class) {
            if (!isset($map[$class])) {
                $map[$class] = $file;
            }
        }
    }

    return $map;
}

/**
 * Extrait les noms pleinement qualifies des classes, interfaces, traits et
 * enums declares dans un fichier. On passe par token_get_all plutot que par
 * une expression reguliere, afin d'ignorer correctement "::class", les classes
 * anonymes et les occurrences en commentaire.
 */
function extractClassNames(string $file): array
{
    $src = @file_get_contents($file);
    if ($src === false || strpos($src, '<?') === false) {
        return [];
    }

    $tokens = @token_get_all($src);
    if (!is_array($tokens)) {
        return [];
    }

    $names = [];
    $namespace = '';
    $count = count($tokens);
    $skip = [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT];

    for ($i = 0; $i < $count; $i++) {
        $token = $tokens[$i];
        if (!is_array($token)) {
            continue;
        }

        if ($token[0] === T_NAMESPACE) {
            $namespace = '';
            for ($j = $i + 1; $j < $count; $j++) {
                if ($tokens[$j] === ';' || $tokens[$j] === '{') {
                    break;
                }
                if (!is_array($tokens[$j])) {
                    continue;
                }
                $id = $tokens[$j][0];
                if ($id === T_STRING || (defined('T_NAME_QUALIFIED') && $id === T_NAME_QUALIFIED)) {
                    $namespace .= $tokens[$j][1];
                } elseif ($id === T_NS_SEPARATOR) {
                    $namespace .= '\\';
                }
            }
            $namespace = trim($namespace, '\\');
            continue;
        }

        $isDeclaration = $token[0] === T_CLASS
            || $token[0] === T_INTERFACE
            || $token[0] === T_TRAIT
            || (defined('T_ENUM') && $token[0] === T_ENUM);

        if (!$isDeclaration) {
            continue;
        }

        // "Foo::class" et "new class {...}" ne declarent rien.
        $prev = $i - 1;
        while ($prev >= 0 && is_array($tokens[$prev]) && in_array($tokens[$prev][0], $skip, true)) {
            $prev--;
        }
        if ($prev >= 0 && is_array($tokens[$prev])
            && ($tokens[$prev][0] === T_DOUBLE_COLON || $tokens[$prev][0] === T_NEW)) {
            continue;
        }

        for ($j = $i + 1; $j < $count; $j++) {
            if (is_array($tokens[$j]) && in_array($tokens[$j][0], $skip, true)) {
                continue;
            }
            if (is_array($tokens[$j]) && $tokens[$j][0] === T_STRING) {
                $names[] = $namespace === '' ? $tokens[$j][1] : $namespace . '\\' . $tokens[$j][1];
            }
            break;
        }
    }

    return $names;
}
